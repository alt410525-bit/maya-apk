#!/usr/bin/env bash
# Maya Clone Supabase Setup Script
# Creates Supabase project, applies schema.sql, and enables RLS policies
# Outputs connection params for local.properties

set -euo pipefail

# Colors for output
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
NC='\033[0m' # No Color

log_info() { echo -e "${BLUE}[INFO]${NC} $*"; }
log_success() { echo -e "${GREEN}[SUCCESS]${NC} $*"; }
log_warn() { echo -e "${YELLOW}[WARN]${NC} $*"; }
log_error() { echo -e "${RED}[ERROR]${NC} $*"; }

# Configuration
PROJECT_NAME="maya-clone"
SCHEMA_FILE="/root/maya_clone_project/supabase/schema.sql"
OUTPUT_FILE="/root/maya_clone_project/app/local.properties"
SUPABASE_DIR="/root/maya_clone_project/supabase"

# Ensure supabase CLI is available
if ! command -v supabase &> /dev/null; then
    log_error "Supabase CLI not found. Install with: npm install -g supabase"
    log_error "Or download from: https://github.com/supabase/cli/releases"
    exit 1
fi

# Ensure we're logged in
if ! supabase projects list &> /dev/null; then
    log_error "Not logged in to Supabase. Run: supabase login"
    exit 1
fi

# Create supabase directory if it doesn't exist
mkdir -p "$SUPABASE_DIR"

# Main setup
log_info "Starting Supabase setup for project: $PROJECT_NAME"

# Check if project already exists
EXISTING_PROJECT=$(supabase projects list --output json 2>/dev/null | jq -r ".[] | select(.name == \"$PROJECT_NAME\") | .id" | head -1)

if [ -n "$EXISTING_PROJECT" ]; then
    log_warn "Project '$PROJECT_NAME' already exists (ID: $EXISTING_PROJECT)"
    read -p "Use existing project? (y/n): " -n 1 -r
    echo
    if [[ ! $REPLY =~ ^[Yy]$ ]]; then
        log_error "Aborted by user"
        exit 1
    fi
    PROJECT_ID="$EXISTING_PROJECT"
else
    # Create new project
    log_info "Creating new Supabase project: $PROJECT_NAME"
    PROJECT_OUTPUT=$(supabase projects create "$PROJECT_NAME" --org "$(supabase orgs list --output json | jq -r '.[0].id')" --region "us-east-1" --output json)
    PROJECT_ID=$(echo "$PROJECT_OUTPUT" | jq -r '.id')
    log_success "Project created with ID: $PROJECT_ID"
fi

# Link local project to remote
log_info "Linking local project to remote..."
supabase link --project-ref "$PROJECT_ID"

# Get project URL and keys
log_info "Fetching project connection details..."
PROJECT_DETAILS=$(supabase projects api-keys --project-ref "$PROJECT_ID" --output json)
PROJECT_URL=$(echo "$PROJECT_DETAILS" | jq -r '.url')
ANON_KEY=$(echo "$PROJECT_DETAILS" | jq -r '.anon_key')
SERVICE_ROLE_KEY=$(echo "$PROJECT_DETAILS" | jq -r '.service_role_key')

# Apply database schema
log_info "Applying database schema from $SCHEMA_FILE..."
supabase db push --project-ref "$PROJECT_ID" --include-all

# Alternative: Run schema directly via psql if db push doesn't work
# For now, we'll also apply the schema SQL file directly
log_info "Applying schema.sql via SQL..."
cat "$SCHEMA_FILE" | supabase db execute --project-ref "$PROJECT_ID" --file -

# Verify RLS is enabled
log_info "Verifying RLS policies..."
VERIFY_SQL="SELECT schemaname, tablename, rowsecurity FROM pg_tables WHERE schemaname = 'public' AND rowsecurity = true;"
supabase db execute --project-ref "$PROJECT_ID" --command "$VERIFY_SQL"

# Write connection params to local.properties
log_info "Writing connection parameters to $OUTPUT_FILE..."
cat > "$OUTPUT_FILE" <<EOF
# Maya Clone Supabase Configuration
# Generated by supabase/setup.sh on $(date)
# DO NOT COMMIT THIS FILE - contains secrets

# Supabase Project
supabase.project.id=$PROJECT_ID
supabase.project.url=$PROJECT_URL
supabase.project.anon_key=$ANON_KEY
supabase.project.service_role_key=$SERVICE_ROLE_KEY

# Database (for direct connections if needed)
supabase.db.url=postgresql://postgres:$SERVICE_ROLE_KEY@db.$PROJECT_ID.supabase.co:5432/postgres
EOF

log_success "Connection parameters written to $OUTPUT_FILE"

# Print summary
echo
log_success "=== Supabase Setup Complete ==="
echo
echo "Project ID: $PROJECT_ID"
echo "Project URL: $PROJECT_URL"
echo "Anon Key: $ANON_KEY"
echo "Service Role Key: $SERVICE_ROLE_KEY"
echo
echo "Connection params saved to: $OUTPUT_FILE"
echo
log_info "Next steps:"
echo "  1. Add $OUTPUT_FILE to .gitignore"
echo "  2. Configure Android app with these values"
echo "  3. Test connection from app"
echo "  4. Set up Supabase Auth providers (Email, Google) in dashboard"